#!/usr/bin/env python3
"""Run clang-include-cleaner over every file in compile_commands.json to find
unused #include directives, and write results to a report file.

Usage:
    python3 scripts/find_unused_includes.py [-j JOBS] [-o OUTPUT]
"""
import argparse
import json
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

BUILD_DIR = "/home/tamago/psi4/objdir_psidev/psi4-core-prefix/src/psi4-core-build"
COMPILE_COMMANDS = Path(BUILD_DIR) / "compile_commands.json"


def analyze_file(path: str):
    """Return (path, list_of_unused_include_lines, error_or_none)."""
    try:
        proc = subprocess.run(
            [
                "clang-include-cleaner",
                "-p",
                BUILD_DIR,
                "--disable-insert",
                "--print=changes",
                path,
            ],
            capture_output=True,
            text=True,
            timeout=180,
        )
    except subprocess.TimeoutExpired:
        return path, [], "TIMEOUT"

    if proc.returncode != 0:
        # Keep stderr for diagnostics but don't fail the whole run.
        return path, [], proc.stderr.strip().splitlines()[-1] if proc.stderr else f"exit {proc.returncode}"

    unused = [line[2:].strip() for line in proc.stdout.splitlines() if line.startswith("- ")]
    return path, unused, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-j", "--jobs", type=int, default=12)
    ap.add_argument("-o", "--output", default="unused_includes.txt")
    ap.add_argument("--limit", type=int, default=None, help="only process first N files (debug)")
    args = ap.parse_args()

    entries = json.loads(COMPILE_COMMANDS.read_text())
    files = [e["file"] for e in entries]
    if args.limit:
        files = files[: args.limit]

    results = {}
    errors = {}
    done = 0
    total = len(files)

    with ThreadPoolExecutor(max_workers=args.jobs) as ex:
        futures = {ex.submit(analyze_file, f): f for f in files}
        for fut in as_completed(futures):
            path, unused, err = fut.result()
            done += 1
            if err:
                errors[path] = err
            elif unused:
                results[path] = unused
            print(f"[{done}/{total}] {path} -> {len(unused)} unused" + (f" (ERROR: {err})" if err else ""), file=sys.stderr)

    with open(args.output, "w") as f:
        f.write(f"# Unused includes report\n")
        f.write(f"# Generated by clang-include-cleaner over {total} files\n")
        f.write(f"# Files with at least one unused include: {len(results)}\n")
        f.write(f"# Files with errors: {len(errors)}\n\n")
        for path in sorted(results):
            f.write(f"{path}\n")
            for inc in results[path]:
                f.write(f"    - {inc}\n")
            f.write("\n")

        if errors:
            f.write("\n# ==== ERRORS ====\n")
            for path in sorted(errors):
                f.write(f"{path}: {errors[path]}\n")

    print(f"\nDone. {len(results)}/{total} files have unused includes. {len(errors)} errors.", file=sys.stderr)
    print(f"Report written to {args.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
