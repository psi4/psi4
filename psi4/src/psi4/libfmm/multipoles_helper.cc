// The real-spherical-harmonic rotation matrices are generated by the direct
// recursion of Ivanic and Ruedenberg, J. Phys. Chem. 100, 6342 (1996),
// doi:10.1021/jp953350u, with the corrections in J. Phys. Chem. A 102, 9099
// (1998), doi:10.1021/jp9833350. Simmonett et al., J. Chem. Phys. 140,
// 184101 (2014), doi:10.1063/1.4873920, describe the corresponding rotation
// of spherical-harmonic multipoles into a quasi-internal frame.
MultipoleRotationFactory::MultipoleRotationFactory(Vector3 source_center, Vector3 target_center, int lmax) {
    if (lmax < 0) {
        throw PSIEXCEPTION("MultipoleRotationFactory requires a nonnegative maximum angular momentum.");
    }
    lmax_ = lmax;
    Vector3 displacement = source_center - target_center;
    double distance = displacement.norm();
    if (distance <= std::numeric_limits<double>::epsilon()) {
        throw PSIEXCEPTION("MultipoleRotationFactory requires distinct source and target centers.");
    }

    Vector3 z_axis = displacement / distance;
    Vector3 x_axis_seed(z_axis);

    if (source_center[1] == target_center[1] && source_center[2] == target_center[2]) {
        x_axis_seed[1] += 1.0;
    } else {
        x_axis_seed[0] += 1.0;
    }

    double projection = x_axis_seed.dot(z_axis);
    x_axis_seed -= (z_axis * projection);

    Vector3 x_axis = x_axis_seed / x_axis_seed.norm();
    Vector3 y_axis = z_axis.cross(x_axis);

    Uz_ = std::make_shared<Matrix>("Uz Matrix", 3, 3);

    for (int i = 0; i < 3; i++) {
        Uz_->set(0, i, x_axis[i]);
        Uz_->set(1, i, y_axis[i]);
        Uz_->set(2, i, z_axis[i]);
    }

    D_cache_.resize(lmax_ + 1);
}

double MultipoleRotationFactory::U(int l, int m, int M) {
    return P(0, l, m, M);
}

double MultipoleRotationFactory::V(int l, int m, int M) {
    double val;
    if (m == 0) {
        val = P(1, l, 1, M) + P(-1, l, -1, M);
    } else if (m > 0) {
        if (m == 1) {
            val = std::sqrt(2.0) * P(1, l, m-1, M);
        } else {
            val = P(1, l, m-1, M) - P(-1, l, -m+1, M);
        }
    } else {
        if (m == -1) {
            val = std::sqrt(2.0) * P(-1, l, -m-1, M);
        } else {
            val = P(1, l, m+1, M) + P(-1, l, -m-1, M);
        }
    }
    return val;
}

double MultipoleRotationFactory::W(int l, int m, int M) {
    double val;
    if (m == 0) {
        val = 0.0;
    } else if (m > 0) {
        val = P(1, l, m+1, M) + P(-1, l, -m-1, M);
    } else {
        val = P(1, l, m-1, M) - P(-1, l, -m+1, M);
    }
    return val;
}

double MultipoleRotationFactory::P(int i, int l, int mu, int M) {
    int i_address = m_addr(i);
    SharedMatrix rank_one_rotation = get_D(1);
    SharedMatrix lower_rank_rotation = get_D(l - 1);
    if (std::abs(M) < l) {
        return rank_one_rotation->get(i_address, 0) * lower_rank_rotation->get(m_addr(mu), m_addr(M));
    } else if (M == l) {
        return rank_one_rotation->get(i_address, 1) * lower_rank_rotation->get(m_addr(mu), m_addr(M - 1)) -
               rank_one_rotation->get(i_address, 2) * lower_rank_rotation->get(m_addr(mu), m_addr(-M + 1));
    } else {
        return rank_one_rotation->get(i_address, 1) * lower_rank_rotation->get(m_addr(mu), m_addr(M + 1)) +
               rank_one_rotation->get(i_address, 2) * lower_rank_rotation->get(m_addr(mu), m_addr(-M - 1));
    }
}

SharedMatrix MultipoleRotationFactory::get_D(int l) {
    if (l > lmax_) {
        throw PsiException("Requested rotation rank exceeds the configured maximum angular momentum.", __FILE__,
                           __LINE__);
    }

    if (D_cache_[l]) {
        return D_cache_[l];
    }

    SharedMatrix rotation_matrix;

    if (l == 0) {
        rotation_matrix = std::make_shared<Matrix>("D Rotation Matrix", 1, 1);
        rotation_matrix->set(0, 0, 1.0);
    } else if (l == 1) {
        rotation_matrix = std::make_shared<Matrix>("D Rotation Matrix", 3, 3);
        std::vector<int> permute {2, 0, 1};
        for (int i = 0; i < 3; i++) {
            int ip = permute[i];
            for (int j = 0; j < 3; j++) {
                int jp = permute[j];
                rotation_matrix->set(i, j, Uz_->get(ip, jp));
            }
        }
    } else {
        rotation_matrix = std::make_shared<Matrix>("D Rotation Matrix", 2 * l + 1, 2 * l + 1);

        for (int m1 = -l; m1 <= l; m1++) {
            int k1 = m_addr(m1);
            for (int m2 = -l; m2 <= l; m2++) {
                int k2 = m_addr(m2);
                double U_term = u(l, m1, m2);
                if (U_term != 0.0) U_term *= U(l, m1, m2);
                double V_term = v(l, m1, m2);
                if (V_term != 0.0) V_term *= V(l, m1, m2);
                double W_term = w(l, m1, m2);
                if (W_term != 0.0) W_term *= W(l, m1, m2);
                rotation_matrix->set(k1, k2, U_term + V_term + W_term);
            }
        }
    }

    D_cache_[l] = rotation_matrix;
    return D_cache_[l];
}

HarmonicCoefficients::HarmonicCoefficients(int lmax, SolidHarmonicsType type) {
    if (lmax < 0) {
        throw PSIEXCEPTION("HarmonicCoefficients requires a nonnegative maximum angular momentum.");
    }
    lmax_ = lmax;
    type_ = type;

    Rc_.resize(lmax_+1);
    Rs_.resize(lmax_+1);
    mpole_terms_.resize(lmax_+1);

    for (int l = 0; l <= lmax_; l++) {
        Rc_[l].resize(l+1);
        Rs_[l].resize(l+1);
        mpole_terms_[l].resize(2*l+1);
    }

    if (type_ == Regular) compute_terms_regular();
    if (type_ == Irregular) compute_terms_irregular();
}

void HarmonicCoefficients::compute_terms_irregular() {
    throw FeatureNotImplemented("libfmm", "RealSolidHarmonics::compute_terms_irregular()", __FILE__, __LINE__);
}

void HarmonicCoefficients::compute_terms_regular() {

    // These Cartesian-polynomial recurrences generate the cosine- and
    // sine-like scaled regular solid harmonics in the convention summarized by
    // Helgaker, Jorgensen, and Olsen, Molecular Electronic-Structure Theory
    // (Wiley, 2000), doi:10.1002/9781119019572, pp. 412-414. Equivalent
    // real-scaled definitions and recurrences are given by Watson et al.,
    // J. Chem. Phys. 121, 2915 (2004),
    // doi:10.1063/1.1771639, Eqs. (32)-(50).

    for (int l = 0; l <= lmax_; l++) {
        int ncl = ncart(l);

        if (l == 0) {
            Rc_[0][0][0] = 1.0;
            Rs_[0][0][0] = 0.0;
        } else {
            // m < l-1 terms
            for (int m = 0; m < l-1; m++) {
                double denom = (l+m)*(l-m);

                // Rc_[l-1][m] contributions to Rc_[l][m]
                for (const std::pair<int, double>& rpair : Rc_[l-1][m]) {
                    int ncl1 = ncart(l-1);
                    int ind = rpair.first;
                    double coef = rpair.second;
                    if (std::abs(coef) < 1.0e-16) continue;
                    int a = ind / (ncl1*ncl1);
                    int bc = ind % (ncl1*ncl1);
                    int b = bc / ncl1;
                    int c = bc % ncl1;

                    int newind = a * ncl * ncl + b * ncl + (c+1);

                    Rc_[l][m][newind] += coef * (2*l-1) / denom;

                }

                // Rc_[l-2][m] contributions to Rc_[l][m]
                for (const std::pair<int, double>& rpair : Rc_[l-2][m]) {
                    int ncl2 = ncart(l-2);
                    int ind = rpair.first;
                    double coef = rpair.second;
                    if (std::abs(coef) < 1.0e-16) continue;
                    int a = ind / (ncl2*ncl2);
                    int bc = ind % (ncl2*ncl2);
                    int b = bc / ncl2;
                    int c = bc % ncl2;

                    int newind1 = (a+2) * ncl * ncl + b * ncl + c;
                    Rc_[l][m][newind1] += -coef / denom;
                    int newind2 = a * ncl * ncl + (b+2) * ncl + c;
                    Rc_[l][m][newind2] += -coef / denom;
                    int newind3 = a * ncl * ncl + b * ncl + (c+2);
                    Rc_[l][m][newind3] += -coef / denom;

                }

                // Rs_[l-1][m] contributions to Rs_[l][m]
                for (const std::pair<int, double>& rpair : Rs_[l-1][m]) {
                    int ncl1 = ncart(l-1);
                    int ind = rpair.first;
                    double coef = rpair.second;
                    if (std::abs(coef) < 1.0e-16) continue;
                    int a = ind / (ncl1*ncl1);
                    int bc = ind % (ncl1*ncl1);
                    int b = bc / ncl1;
                    int c = bc % ncl1;

                    int newind = a * ncl * ncl + b * ncl + (c+1);

                    Rs_[l][m][newind] += coef * (2*l-1) / denom;

                }

                // Rs_[l-2][m] contributions to Rs_[l][m]
                for (const std::pair<int, double>& rpair : Rs_[l-2][m]) {
                    int ncl2 = ncart(l-2);
                    int ind = rpair.first;
                    double coef = rpair.second;
                    if (std::abs(coef) < 1.0e-16) continue;
                    int a = ind / (ncl2*ncl2);
                    int bc = ind % (ncl2*ncl2);
                    int b = bc / ncl2;
                    int c = bc % ncl2;

                    int newind1 = (a+2) * ncl * ncl + b * ncl + c;
                    Rs_[l][m][newind1] += -coef / denom;
                    int newind2 = a * ncl * ncl + (b+2) * ncl + c;
                    Rs_[l][m][newind2] += -coef / denom;
                    int newind3 = a * ncl * ncl + b * ncl + (c+2);
                    Rs_[l][m][newind3] += -coef / denom;

                }
            }

            // => m = l-1 <= //

            // Rc[l][l-1]
            for (const std::pair<int, double>& rpair : Rc_[l-1][l-1]) {
                int ncl1 = ncart(l-1);
                int ind = rpair.first;
                double coef = rpair.second;
                if (std::abs(coef) < 1.0e-16) continue;
                int a = ind / (ncl1*ncl1);
                int bc = ind % (ncl1*ncl1);
                int b = bc / ncl1;
                int c = bc % ncl1;

                int newind = a * ncl * ncl + b * ncl + (c+1);

                Rc_[l][l-1][newind] += coef;
            }

            // Rs[l][l-1]
            for (const std::pair<int, double>& rpair : Rs_[l-1][l-1]) {
                int ncl1 = ncart(l-1);
                int ind = rpair.first;
                double coef = rpair.second;
                if (std::abs(coef) < 1.0e-16) continue;
                int a = ind / (ncl1*ncl1);
                int bc = ind % (ncl1*ncl1);
                int b = bc / ncl1;
                int c = bc % ncl1;

                int newind = a * ncl * ncl + b * ncl + (c+1);

                Rs_[l][l-1][newind] += coef;
            }

            // => m = l <= //

            // Rc[l-1][l-1] contribution to Rc[l][l]
            for (const std::pair<int, double>& rpair : Rc_[l-1][l-1]) {
                int ncl1 = ncart(l-1);
                int ind = rpair.first;
                double coef = rpair.second;
                if (std::abs(coef) < 1.0e-16) continue;
                int a = ind / (ncl1*ncl1);
                int bc = ind % (ncl1*ncl1);
                int b = bc / ncl1;
                int c = bc % ncl1;

                int newind = (a+1) * ncl * ncl + b * ncl + c;

                Rc_[l][l][newind] += -coef/(2*l);

            }

            // Rs[l-1][l-1] contribution to Rc[l][l]
            for (const std::pair<int, double>& rpair : Rs_[l-1][l-1]) {
                int ncl1 = ncart(l-1);
                int ind = rpair.first;
                double coef = rpair.second;
                if (std::abs(coef) < 1.0e-16) continue;
                int a = ind / (ncl1*ncl1);
                int bc = ind % (ncl1*ncl1);
                int b = bc / ncl1;
                int c = bc % ncl1;

                int newind = a * ncl * ncl + (b+1) * ncl + c;

                Rc_[l][l][newind] += coef/(2*l);

            }

            // Rc[l-1][l-1] contribution to Rs[l][l]
            for (const std::pair<int, double>& rpair : Rc_[l-1][l-1]) {
                int ncl1 = ncart(l-1);
                int ind = rpair.first;
                double coef = rpair.second;
                if (std::abs(coef) < 1.0e-16) continue;
                int a = ind / (ncl1*ncl1);
                int bc = ind % (ncl1*ncl1);
                int b = bc / ncl1;
                int c = bc % ncl1;

                int newind = a * ncl * ncl + (b+1) * ncl + c;

                Rs_[l][l][newind] += -coef/(2*l);

            }

            // Rs[l-1][l-1] contribution to Rs[l][l]
            for (const std::pair<int, double>& rpair : Rs_[l-1][l-1]) {
                int ncl1 = ncart(l-1);
                int ind = rpair.first;
                double coef = rpair.second;
                if (std::abs(coef) < 1.0e-16) continue;
                int a = ind / (ncl1*ncl1);
                int bc = ind % (ncl1*ncl1);
                int b = bc / ncl1;
                int c = bc % ncl1;

                int newind = (a+1) * ncl * ncl + b * ncl + c;

                Rs_[l][l][newind] += -coef/(2*l);

            }
        }

        for (int m = -l; m <= l; m++) {
            // m is signed address
            // mu is unsigned address
            int mu = m_addr(m);
            double prefactor = 1.0;

            if ((mu == 0) || (mu % 2 == 1)) {
                if (mu == 0) {
                    prefactor = cfmm_factorial(l);
                } else {
                    prefactor = std::pow(-1.0, (double) m) * std::sqrt(2.0 * cfmm_factorial(l-m) * cfmm_factorial(l+m));
                }
                for (const std::pair<int, double>& rpair : Rc_[l][m]) {
                    int ind = rpair.first;
                    double coef = rpair.second;
                    if (std::abs(coef) < 1.0e-16) continue;
                    mpole_terms_[l][mu][ind] = prefactor * coef;
                }

            } else {
                prefactor = std::pow(-1.0, (double) m) * std::sqrt(2.0 * cfmm_factorial(l-m) * cfmm_factorial(l+m));
                for (const std::pair<int, double>& rpair : Rs_[l][-m]) {
                    int ind = rpair.first;
                    double coef = rpair.second;
                    if (std::abs(coef) < 1.0e-16) continue;
                    mpole_terms_[l][mu][ind] = prefactor * coef;
                }
            }
        }
    }
}

RealSolidHarmonics::RealSolidHarmonics(int lmax, Vector3 center, SolidHarmonicsType type) {
    if (lmax < 0) {
        throw PSIEXCEPTION("RealSolidHarmonics requires a nonnegative maximum angular momentum.");
    }
    lmax_ = lmax;
    center_ = center;
    type_ = type;

    // Set all multipoles to zero
    Ylm_.resize(lmax_+1);

    for (int l = 0; l <= lmax_; l++) {
        Ylm_[l].resize(2*l+1, 0.0);
    }

}

std::shared_ptr<RealSolidHarmonics> RealSolidHarmonics::copy() {
    auto harmonics_copy = std::make_shared<RealSolidHarmonics>(lmax_, center_, type_);
    for (int l = 0; l <= lmax_; l++) {
        for (int mu = 0; mu < 2*l+1; mu++) {
            harmonics_copy->Ylm_[l][mu] = Ylm_[l][mu];
        }
    }
    return harmonics_copy;
}

void RealSolidHarmonics::add(const RealSolidHarmonics& other) {
    for (int l = 0; l <= lmax_; l++) {
        for (int mu = 0; mu < 2*l+1; mu++) {
#pragma omp atomic
            Ylm_[l][mu] += other.Ylm_[l][mu];
        }
    }
}

void RealSolidHarmonics::add(const std::shared_ptr<RealSolidHarmonics>& other) {
    this->add(*other);
}

double RealSolidHarmonics::dot(const RealSolidHarmonics& other) {
    double result = 0.0;
    for (int l = 0; l <= lmax_; l++) {
        for (int mu = 0; mu < 2*l+1; mu++) {
            result += Ylm_[l][mu] * other.Ylm_[l][mu];
        }
    }
    return result;
}

double RealSolidHarmonics::dot(const std::shared_ptr<RealSolidHarmonics>& other) {
    return this->dot(*other);
}

void RealSolidHarmonics::scale(double factor) {
    for (int l = 0; l <= lmax_; l++) {
        for (int mu = 0; mu < 2*l+1; mu++) {
            Ylm_[l][mu] *= factor;
        }
    }
}

std::shared_ptr<RealSolidHarmonics> RealSolidHarmonics::translate(const Vector3& new_center) {
    if ((new_center - center_).norm() <= std::numeric_limits<double>::epsilon()) return copy();

    switch (type_) {
        case Regular:
            return translate_regular(new_center);
        case Irregular:
            return translate_irregular(new_center);
        default:
            throw PSIEXCEPTION("RealSolidHarmonics has an invalid solid-harmonic type.");
    }
}

std::shared_ptr<RealSolidHarmonics> RealSolidHarmonics::translate_irregular(Vector3 new_center) {
    // Translation is evaluated in a frame whose z axis is parallel to the
    // center displacement. The axial binomial form below is the irregular
    // solid-harmonic addition theorem; see Helgaker, Jorgensen, and Olsen,
    // Molecular Electronic-Structure Theory (Wiley, 2000),
    // doi:10.1002/9781119019572, pp. 412-414.
    // The rotate-translate-back-rotate construction follows the same scaled
    // real-harmonic conventions as Watson et al., J. Chem. Phys. 121, 2915
    // (2004), doi:10.1063/1.1771639, Eqs. (53)-(59).
    auto translated_harmonics = std::make_shared<RealSolidHarmonics>(lmax_, new_center, Irregular);
    auto rotation_factory = std::make_shared<MultipoleRotationFactory>(center_, new_center, lmax_);

    Vector3 translation = new_center - center_;
    double translation_distance = translation.norm();

    std::vector<std::vector<double>> rotated_multipoles(lmax_ + 1);
    std::vector<std::vector<double>> translated_rotated_multipoles(lmax_ + 1);

    // Rotate the multipoles so that the translation lies along the z axis.
    for (int l = 0; l <= lmax_; l++) {
        rotated_multipoles[l].resize(2 * l + 1, 0.0);
        int dimension = 2 * l + 1;
        SharedMatrix rotation_matrix = rotation_factory->get_D(l);
        for (int i = 0; i < dimension; i++) {
            for (int j = 0; j < dimension; j++) {
                rotated_multipoles[l][i] += rotation_matrix->get(i, j) * Ylm_[l][j];
            }
        }
    }

    // Apply the irregular-to-irregular axial translation.
    for (int l = 0; l <= lmax_; l++) {
        translated_rotated_multipoles[l].resize(2 * l + 1, 0.0);
        for (int j = l; j <= lmax_; j++) {
            for (int m = -l; m <= l; m++) {
                int mu = m_addr(m);
                double translation_coefficient =
                    std::sqrt((double)choose(j + m, l + m) * choose(j - m, l - m));

                translated_rotated_multipoles[l][mu] +=
                    translation_coefficient * std::pow(translation_distance, j - l) * rotated_multipoles[j][mu];
            }
        }
    }

    // Rotate the translated multipoles back into the laboratory frame.
    for (int l = 0; l <= lmax_; l++) {
        SharedMatrix rotation_matrix = rotation_factory->get_D(l);
        int dimension = 2 * l + 1;
        for (int i = 0; i < dimension; i++) {
            for (int j = 0; j < dimension; j++) {
                translated_harmonics->Ylm_[l][i] +=
                    rotation_matrix->get(j, i) * translated_rotated_multipoles[l][j];
            }
        }
    }

    return translated_harmonics;
}

std::shared_ptr<RealSolidHarmonics> RealSolidHarmonics::translate_regular(Vector3 new_center) {
    // This is the regular-solid-harmonic addition theorem in an axially
    // aligned frame. See Helgaker, Jorgensen, and Olsen, Molecular
    // Electronic-Structure Theory (Wiley, 2000), doi:10.1002/9781119019572,
    // pp. 412-414, and Watson et al., J. Chem. Phys. 121, 2915 (2004),
    // doi:10.1063/1.1771639,
    // Eqs. (53)-(59).
    auto translated_harmonics = std::make_shared<RealSolidHarmonics>(lmax_, new_center, Regular);
    auto rotation_factory = std::make_shared<MultipoleRotationFactory>(center_, new_center, lmax_);

    Vector3 translation = new_center - center_;
    double translation_distance = translation.norm();

    std::vector<std::vector<double>> rotated_multipoles(lmax_ + 1);
    std::vector<std::vector<double>> translated_rotated_multipoles(lmax_ + 1);

    for (int l = 0; l <= lmax_; l++) {
        rotated_multipoles[l].resize(2 * l + 1, 0.0);
        translated_rotated_multipoles[l].resize(2 * l + 1, 0.0);
    }

    // Rotate the multipoles so that the translation lies along the z axis.
    for (int l = 0; l <= lmax_; l++) {
        int dimension = 2 * l + 1;
        SharedMatrix rotation_matrix = rotation_factory->get_D(l);
        for (int i = 0; i < dimension; i++) {
            for (int j = 0; j < dimension; j++) {
                rotated_multipoles[l][i] += rotation_matrix->get(i, j) * Ylm_[l][j];
            }
        }
    }

    // Apply the regular-to-regular axial translation.
    for (int l = 0; l <= lmax_; l++) {
        for (int j = 0; j <= l; j++) {
            for (int m = -j; m <= j; m++) {
                int mu = m_addr(m);
                double translation_coefficient =
                    std::sqrt((double)choose(l + m, j + m) * choose(l - m, j - m));
                translated_rotated_multipoles[l][mu] +=
                    translation_coefficient * std::pow(-translation_distance, l - j) * rotated_multipoles[j][mu];
            }
        }
    }

    // Rotate the translated multipoles back into the laboratory frame.
    for (int l = 0; l <= lmax_; l++) {
        SharedMatrix rotation_matrix = rotation_factory->get_D(l);
        int dimension = 2 * l + 1;
        for (int i = 0; i < dimension; i++) {
            for (int j = 0; j < dimension; j++) {
                translated_harmonics->Ylm_[l][i] +=
                    rotation_matrix->get(j, i) * translated_rotated_multipoles[l][j];
            }
        }
    }

    return translated_harmonics;
}

// Evaluate the axial real-solid-harmonic interaction tensor. The general
// bipolar expansion and irregular-harmonic tensor are discussed by Helgaker,
// Jorgensen, and Olsen, Molecular Electronic-Structure Theory (Wiley, 2000),
// doi:10.1002/9781119019572, pp. 412-414. This aligned-frame reduction is
// equivalent to Watson et al.,
// J. Chem. Phys. 121, 2915 (2004), doi:10.1063/1.1771639, Eqs. (60)-(72).
SharedVector RealSolidHarmonics::build_T_spherical(int la, int lb, double distance) {
    if (distance <= std::numeric_limits<double>::epsilon()) {
        throw PSIEXCEPTION("The solid-harmonic interaction tensor requires nonzero separation.");
    }
    int lmin = std::min(la, lb);
    SharedVector interaction_tensor = std::make_shared<Vector>(2 * lmin + 1);
    double denominator = std::pow(distance, (double)la + lb + 1);

    for (int m = -lmin; m <= lmin; m++) {
        int mu = m_addr(m);
        double interaction_value = std::pow(-1.0, (double)(lb - m)) *
                                   std::sqrt((double)choose(la + lb, la + m) * choose(la + lb, la - m)) /
                                   denominator;
        interaction_tensor->set(mu, interaction_value);
    }

    return interaction_tensor;
}

std::shared_ptr<RealSolidHarmonics> RealSolidHarmonics::far_field_vector(const Vector3& far_center) {

    Vector3 displacement = far_center - center_;
    double distance = displacement.norm();
    if (distance <= std::numeric_limits<double>::epsilon()) {
        throw PSIEXCEPTION("A far-field expansion requires distinct source and target centers.");
    }

    auto far_field = std::make_shared<RealSolidHarmonics>(lmax_, far_center, Irregular);
    auto rotation_factory = std::make_shared<MultipoleRotationFactory>(far_center, center_, lmax_);

    for (int l = 0; l <= lmax_; l++) {
        for (int j = 0; j <= lmax_; j++) {
            SharedVector interaction_tensor = build_T_spherical(l, j, distance);
            int nterms = 2 * std::min(l, j) + 1;

            std::vector<double> rotated_multipole(2 * j + 1, 0.0);
            SharedMatrix rotation_matrix = rotation_factory->get_D(j);
            for (int u = 0; u < 2 * j + 1; u++) {
                for (int v = 0; v < 2 * j + 1; v++) {
                    rotated_multipole[u] += rotation_matrix->get(u, v) * Ylm_[j][v];
                }
            }

            std::vector<double> temp(nterms, 0.0);
            for (int u = 0; u < nterms; u++) {
                temp[u] = interaction_tensor->get(u) * rotated_multipole[u];
            }

            SharedMatrix rank_l_rotation = rotation_factory->get_D(l);
            for (int r = 0; r < 2 * l + 1; r++) {
                for (int s = 0; s < nterms; s++) {
                    far_field->Ylm_[l][r] += rank_l_rotation->get(s, r) * temp[s];
                }
            }

        }
    }

    return far_field;
}

