"""Regenerate the 3c1e kernels of BatchedPotentialInt in this directory.

Runs the vendored snk_integral_codegen (codegen/, MIT license, see codegen/LICENSE) for every pair of shells
s..f with am(A) >= am(B), on different centers and on the same center, and writes snk_kernels.cc, which compiles
them, and snk_kernels.h, their dispatch tables. Needs SymPy. Run from anywhere:

    python generate.py

The generator emits uncompilable code for an s shell on A with a higher shell on B (P - A is used but not
declared), so only am(A) >= am(B) is generated; BatchedPotentialInt transposes the other orders.
"""

import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "codegen"))
import codegen  # noqa: E402

SHELLS = "SPDF"  # angular momenta 0 .. snk::max_am
PAIRS = [(a, b) for i, a in enumerate(SHELLS) for b in SHELLS[:i + 1]]


def name(a, b, same_center):
    return f"VRR_{a}_{b}" + ("_SAMECENTER" if same_center else "")


def main():
    for a, b in PAIRS:
        for same_center in (False, True):
            codegen.generate_vrr(MSA=a, MSB=b, same_center=same_center, dname=here)

    kernels = [(a, b, sc) for a, b in PAIRS for sc in (False, True)]
    with open(os.path.join(here, "snk_kernels.cc"), "w") as f:
        f.write("// Generated by generate.py: the 3c1e VRR kernels of snk_integral_codegen (MIT license, see\n"
                "// codegen/LICENSE and README.md in this directory), compiled as one translation unit. The kernels\n"
                "// are templates explicitly instantiated for float and double in their .C files.\n\n")
        for a, b, sc in kernels:
            f.write(f'#include "{name(a, b, sc)}.C"\n')

    def table(var, typ, sc):
        rows = []
        for i, a in enumerate(SHELLS):
            cells = [f"&{name(a, b, sc)}<double>" if j <= i else "nullptr" for j, b in enumerate(SHELLS)]
            rows.append("    {" + ", ".join(cells) + "},")
        return f"inline constexpr {typ} {var}[max_am + 1][max_am + 1] = {{\n" + "\n".join(rows) + "\n};\n"

    with open(os.path.join(here, "snk_kernels.h"), "w") as f:
        f.write("// Generated by generate.py: dispatch tables for the 3c1e VRR kernels of snk_integral_codegen (MIT\n"
                "// license, see codegen/LICENSE and README.md in this directory).\n\n"
                "#ifndef SNK_KERNELS_H\n#define SNK_KERNELS_H\n\n")
        for a, b, sc in kernels:
            f.write(f'#include "{name(a, b, sc)}.h"\n')
        f.write(f"""
namespace snk {{

/// Highest angular momentum of a shell with a generated kernel
constexpr int max_am = {len(SHELLS) - 1};

/// Kernel for shells on different centers: integrals[c1 * ncart2 + c2][g] for the Cartesian components c1, c2 in
/// CCA order, from per primitive pair: the Obara-Saika seeds (2 pi / p) U_p F_N(T_g) [prim][N][g], p [prim],
/// P - G [prim][g] for x, y, z, and P - A [prim] for x, y, z; and A - B.
using VRRKernel = void (*)(double*, const double*, const double*, const double*, const double*, const double*,
                           const double*, const double*, const double*, double, double, double, int, int);
/// Kernel for shells on the same center: as VRRKernel, without P - A and A - B.
using VRRKernelSameCenter = void (*)(double*, const double*, const double*, const double*, const double*,
                                     const double*, int, int);

// Only for am(A) >= am(B), see generate.py.
""")
        f.write(table("vrr", "VRRKernel", False) + "\n" + table("vrr_same_center", "VRRKernelSameCenter", True))
        f.write("\n}  // namespace snk\n\n#endif  // SNK_KERNELS_H\n")


if __name__ == "__main__":
    main()
