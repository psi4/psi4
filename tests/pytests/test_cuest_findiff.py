_BASE_OPTIONS = {
    # 5-point stencil, i.e. energies at +/-h and +/-2h per coordinate.
    "points": 5,
    "disp_size": 0.005,
    # No symmetry projection of the displacements; the geometries are C1 anyway.
    "fd_project": False,
    "scf_type": "df",
    "df_basis_scf": "def2-universal-JKFIT",
    "basis": "def2-svp",
    "puream": True,
    "dft_nuclear_scheme": "stratmann",
    # The analytic gradient carries grid weight derivatives while the finite
    # difference lets the grid ride along with the nuclei.  Those agree only for
    # a well converged grid, hence the tight quadrature.
    "dft_radial_points": 100,
    "dft_spherical_points": 590,
    "maxiter": 300,
    # Differencing energies over a 0.005 bohr step amplifies SCF noise by ~1/h,
    # so the energies have to be converged well past the gradient tolerance.
    "e_convergence": 10,
    "d_convergence": 9,
    "reference": "rhf",
    "use_cuest": True,
    # Single precision would swamp the finite difference entirely.
    "cuest_mixed_precision": False,
}

# Agreement is limited by grid convergence and by residual SCF noise in the
# displaced energies, not by the 5-point truncation error (~h**4).  Cases with a
# looser requirement carry an explicit "atol" below.
_ATOL_G = 2.0e-5


def _assert_not_wk(functional: str) -> None:
    """Guard the premise of this file: `functional` must not use wK exchange.

    A functional definition growing a range-separation parameter later on would
    otherwise silently drag a wK case into this file.
    """
    definition = dft_builder.dict_functionals[functional]
    superfunc = dft_builder.build_superfunctional_from_dictionary(definition, 1, 1, True)[0]
    assert not superfunc.is_x_lrc(), f"{functional} is range-separated; see test_cuest_range_separated.py"


@pytest.mark.medlong
@uusing("cuest")
@uusing("cuda_cc8")
@pytest.mark.parametrize("inp", [

    # <<<  LDA  >>>
    pytest.param({"functional": "svwn",   "geom": "water"},                                                  id="water_rsvwn"),
    pytest.param({"functional": "svwn",   "geom": "water_cation",       "args": {"reference": "uhf"}},        id="water_cation_usvwn"),

    # <<<  GGA  >>>
    pytest.param({"functional": "blyp",   "geom": "water"},                                                  id="water_rblyp"),
    pytest.param({"functional": "blyp",   "geom": "water_cation",       "args": {"reference": "uhf"}},        id="water_cation_ublyp"),

    # <<<  global hybrid GGA  >>>
    pytest.param({"functional": "b3lyp",  "geom": "water"},                                                  id="water_rb3lyp"),
    pytest.param({"functional": "b3lyp",  "geom": "water_cation",       "args": {"reference": "uhf"}},        id="water_cation_ub3lyp"),

    # <<<  meta-GGA hybrids: exercise the kinetic-energy-density (tau) terms  >>>
    pytest.param({"functional": "m06",    "geom": "water"},                                                  id="water_rm06"),
    pytest.param({"functional": "m06",    "geom": "water_cation",       "args": {"reference": "uhf"}},        id="water_cation_um06"),
    pytest.param({"functional": "pw6b95", "geom": "water"},                                                  id="water_rpw6b95"),
    pytest.param({"functional": "pw6b95", "geom": "water_cation",       "args": {"reference": "uhf"}},        id="water_cation_upw6b95"),

    # <<<  meta-GGA + VV10 nonlocal correlation  >>>
    # The nonlocal kernel has its own coarser internal grid, so it is the least
    # tightly convergent case here.
    pytest.param({"functional": "b97m-v", "geom": "water",                                    "atol": 5e-5}, id="water_rb97m-v"),
    pytest.param({"functional": "b97m-v", "geom": "water_cation",       "args": {"reference": "uhf"}, "atol": 5e-5}, id="water_cation_ub97m-v"),

    # <<<  larger system  >>>
    # 7 atoms means 84 displaced energies per case, so only two functionals here.
    pytest.param({"functional": "b3lyp",  "geom": "methylamine"},                                            id="methylamine_rb3lyp", marks=pytest.mark.long),
    pytest.param({"functional": "b3lyp",  "geom": "methylamine_cation", "args": {"reference": "uhf"}},        id="methylamine_cation_ub3lyp", marks=pytest.mark.long),
    pytest.param({"functional": "b97m-v", "geom": "methylamine",                              "atol": 5e-5}, id="methylamine_rb97m-v", marks=pytest.mark.long),
    pytest.param({"functional": "b97m-v", "geom": "methylamine_cation", "args": {"reference": "uhf"}, "atol": 5e-5}, id="methylamine_cation_ub97m-v", marks=pytest.mark.long),
])
def test_cuest_dft_findiff(inp, request):
    """cuEST analytic DFT gradient == 5-point finite difference of the cuEST energy."""
    psi4.core.set_num_threads(4)

    functional = inp["functional"]
    _assert_not_wk(functional)

    tid = request.node.callspec.id
    atol = inp.get("atol", _ATOL_G)

    molecule = psi4.geometry(_GEOMS[inp["geom"]])
    psi4.set_options({**_BASE_OPTIONS, **inp.get("args", {})})

    G_analytic, wfn = psi4.gradient(functional, molecule=molecule, return_wfn=True, dertype=1)
    G_analytic = np.array(G_analytic)

    psi4.core.clean()

    G_findif = np.array(psi4.gradient(functional, molecule=molecule, dertype=0))

    # A gradient of all zeros would pass the comparison below if the finite
    # difference were also dead, and an XC contribution silently dropping to
    # zero is a real cuEST failure mode (see test_cuest_unsupported_route).
    assert np.abs(G_analytic).max() > 1e-4, f"{tid} analytic gradient is ~zero: {G_analytic}"

    assert compare_values(G_findif, G_analytic, atol, f"{tid} analytic vs 5-point findif gradient"), (
        f"{tid}: cuEST analytic gradient disagrees with 5-point finite difference of the cuEST energy "
        f"(max abs deviation {np.abs(G_analytic - G_findif).max():.3e} > {atol:.1e})\n"
        f"analytic:\n{G_analytic}\nfindif:\n{G_findif}\ndifference:\n{G_analytic - G_findif}"
    )
