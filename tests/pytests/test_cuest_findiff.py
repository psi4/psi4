"""Self-consistency of cuEST analytic DFT gradients against finite differences.

test_cuest.py pins cuEST energies and gradients against stored reference values
taken from regular (non-cuEST) Psi4.  For DFT that yardstick is awkward: Psi4's
CPU analytic DFT gradients omit the grid weight derivatives, so those stored
reference gradients had to be generated by finite difference in the first place
(see the comment at the top of test_cuest.py).

This file takes the complementary, reference-free approach: for each functional
it computes the gradient twice from the *same* cuEST code path -- once
analytically (``dertype=1``) and once as a 5-point finite difference of the
cuEST energy (``dertype=0``) -- and requires the two to agree.  That tests the
derivative implementation itself rather than agreement with another program, and
it is insensitive to whichever grid or nuclear-partition conventions cuEST uses,
since both halves of the comparison use them.

Scope is deliberately limited to functionals that do *not* need long-range
corrected (wK) exchange; ``_assert_not_wk`` enforces that, and range-separated
functionals are covered separately in test_cuest_range_separated.py.  The
functionals below walk up the rungs that have distinct cuEST XC gradient code:
LDA (svwn), GGA (blyp), global hybrid GGA (b3lyp), meta-GGA hybrids that need
tau (m06, pw6b95), and a meta-GGA with VV10 nonlocal correlation (b97m-v).
"""

import numpy as np
import pytest

import psi4
from psi4.driver.procrouting.dft import dft_builder

from utils import *
from addons import uusing

pytestmark = [pytest.mark.psi, pytest.mark.api, pytest.mark.scf, pytest.mark.dft, pytest.mark.findif]

